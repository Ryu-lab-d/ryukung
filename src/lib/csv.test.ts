import { describe, it, expect } from 'vitest'
import { toCsv } from './csv'

describe('toCsv', () => {
  it('คั่นด้วยจุลภาคและครอบเครื่องหมายคำพูดเมื่อมีจุลภาค/ขึ้นบรรทัดใหม่/เครื่องหมายคำพูด', () => {
    expect(toCsv(['a', 'b'], [['x', 1], ['มี,จุลภาค', 'พูดว่า "สวัสดี"'], ['บรรทัด\nใหม่', null]])).toBe(
      'a,b\r\nx,1\r\n"มี,จุลภาค","พูดว่า ""สวัสดี"""\r\n"บรรทัด\nใหม่",'
    )
  })
})
