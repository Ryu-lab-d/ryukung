/** ชื่อยศตามจำนวนด่านที่ผ่าน (0 = ยังไม่ผ่านด่านใดเลย) */
export function rankFor(passedLevels: number): { name: string; icon: string } {
  if (passedLevels <= 0) return { name: 'มือใหม่หัดอบ', icon: '🥣' }
  const lv = QUIZ_LEVELS[Math.min(passedLevels, QUIZ_LEVELS.length) - 1]
  return { name: lv.name, icon: lv.icon }
}
